/// Outcome of disabling a local user.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DisableOutcome {
    /// Disabled, sessions revoked, audited.
    Disabled,
    /// No such enabled user.
    NotFound,
    /// The user is the last enabled Administrator.
    LastAdministrator,
}

/// Disables an enabled user and revokes all sessions in one audited
/// transaction, never the last enabled Administrator.
pub async fn disable_local_user(
    client: &mut Client,
    user_id: &str,
    now: DateTime<Utc>,
    audit: &AuditContext<'_>,
    actor_id: &str,
    actor_kind: &str,
) -> Result<DisableOutcome, StoreError> {
    let tx = client.transaction().await?;
    tx.query_one("SELECT pg_advisory_xact_lock($1)", &[&ACCESS_BINDING_LOCK])
        .await?;
    let last_administrator = tx
        .query_one(
            "SELECT EXISTS (SELECT 1 FROM console_role_bindings b JOIN console_users u USING (user_id)
                 WHERE b.user_id = $1::text::uuid AND u.enabled AND b.role_id = 'admin'
                   AND b.revoked_at IS NULL)",
            &[&user_id],
        )
        .await?
        .get::<_, bool>(0)
        && enabled_administrators(&tx).await? <= 1;
    if last_administrator {
        tx.rollback().await?;
        return Ok(DisableOutcome::LastAdministrator);
    }
    let updated = tx
        .execute(
            "UPDATE console_users SET enabled = false, disabled_at = $2,
                    auth_generation = auth_generation + 1
             WHERE user_id = $1::text::uuid AND enabled",
            &[&user_id, &now],
        )
        .await?;
    if updated == 0 {
        tx.rollback().await?;
        return Ok(DisableOutcome::NotFound);
    }
    tx.execute(
        "UPDATE console_sessions SET revoked_at = COALESCE(revoked_at, $2)
         WHERE user_id = $1::text::uuid",
        &[&user_id, &now],
    )
    .await?;
    append_auth_event(
        &tx,
        audit,
        AuthAuditEvent {
            actor: actor_id,
            action: "user.disabled",
            target: Some(user_id),
            result: "success",
            actor_kind: Some(actor_kind),
            actor_id: Some(actor_id),
            actor_display: None,
            authentication_method: None,
            target_kind: Some("user"),
            target_id: Some(user_id),
            reason_code: Some("administrator_disabled"),
        },
    )
    .await?;
    tx.commit().await?;
    Ok(DisableOutcome::Disabled)
}

/// Stores hash-only one-use local pre-authentication state.
pub async fn create_preauth(client: &Client, state: &NewPreauth<'_>) -> Result<(), StoreError> {
    client
        .execute(
            "INSERT INTO console_preauth
                (token_sha256, csrf_sha256, browser_sha256, created_at, expires_at)
             VALUES ($1, $2, $3, $4, $5)",
            &[
                &state.token_sha256,
                &state.csrf_sha256,
                &state.browser_sha256,
                &state.created_at,
                &state.expires_at,
            ],
        )
        .await?;
    Ok(())
}

/// Atomically consumes pre-authentication state only when all three digests
/// match and it has not expired or been used.
pub async fn consume_preauth(
    client: &Client,
    token_sha256: &[u8],
    csrf_sha256: &[u8],
    browser_sha256: &[u8],
    now: DateTime<Utc>,
) -> Result<bool, StoreError> {
    let updated = client
        .execute(
            "UPDATE console_preauth SET consumed_at = $4
             WHERE token_sha256 = $1 AND csrf_sha256 = $2 AND browser_sha256 = $3
               AND expires_at > $4 AND consumed_at IS NULL",
            &[&token_sha256, &csrf_sha256, &browser_sha256, &now],
        )
        .await?;
    Ok(updated == 1)
}

/// Reports whether any account/source throttle bucket is currently locked.
pub async fn login_is_throttled(
    client: &Client,
    bucket_sha256: &[&[u8]],
    now: DateTime<Utc>,
) -> Result<bool, StoreError> {
    let row = client
        .query_one(
            "SELECT EXISTS (
                SELECT 1 FROM console_auth_throttle
                WHERE bucket_sha256 = ANY($1) AND locked_until > $2
             )",
            &[&bucket_sha256, &now],
        )
        .await?;
    Ok(row.get(0))
}

/// Counts one failure in a throttle bucket: `failure_limit` failures within
/// `window` lock it for `lock_for`. Shared by sign-in and the rule signer.
pub(crate) async fn count_failure(
    client: &impl deadpool_postgres::GenericClient,
    bucket_sha256: &[u8],
    now: DateTime<Utc>,
    window: Duration,
    failure_limit: i32,
    lock_for: Duration,
) -> Result<(), StoreError> {
    client
        .execute(
            "INSERT INTO console_auth_throttle
                (bucket_sha256, window_started_at, failures, locked_until, updated_at)
             VALUES ($1, $2, 1, CASE WHEN $4 <= 1 THEN $5::timestamptz END, $2)
             ON CONFLICT (bucket_sha256) DO UPDATE SET
                window_started_at = CASE
                    WHEN console_auth_throttle.window_started_at <= $3
                    THEN $2 ELSE console_auth_throttle.window_started_at END,
                failures = CASE
                    WHEN console_auth_throttle.window_started_at <= $3
                    THEN 1 ELSE console_auth_throttle.failures + 1 END,
                locked_until = CASE
                    WHEN console_auth_throttle.window_started_at <= $3
                        THEN CASE WHEN $4 <= 1 THEN $5::timestamptz END
                    WHEN console_auth_throttle.failures + 1 >= $4
                        THEN GREATEST(COALESCE(console_auth_throttle.locked_until, $2),
                                      $5)
                    ELSE console_auth_throttle.locked_until END,
                updated_at = $2",
            &[
                &bucket_sha256,
                &now,
                &(now - window),
                &failure_limit,
                &(now + lock_for),
            ],
        )
        .await?;
    Ok(())
}

/// Records one failed login in every supplied bucket. Each bucket carries an
/// independent limit so source-address protection can be less restrictive
/// than the per-account limit.
pub async fn record_login_failure(
    client: &mut Client,
    bucket_sha256: &[&[u8]],
    now: DateTime<Utc>,
    window: Duration,
    failure_limits: &[i32],
    lock_for: Duration,
    audit: &AuditContext<'_>,
) -> Result<(), StoreError> {
    if bucket_sha256.len() != failure_limits.len() || failure_limits.iter().any(|limit| *limit < 1)
    {
        return Err(StoreError::Query);
    }
    let tx = client.transaction().await?;
    for (bucket, failure_limit) in bucket_sha256.iter().zip(failure_limits) {
        count_failure(&tx, bucket, now, window, *failure_limit, lock_for).await?;
    }
    append_auth_event(
        &tx,
        audit,
        AuthAuditEvent {
            actor: "console-login",
            action: "auth.login.failed",
            target: None,
            result: "failure",
            actor_kind: Some("anonymous"),
            actor_id: None,
            actor_display: None,
            authentication_method: Some("local_password"),
            target_kind: None,
            target_id: None,
            reason_code: Some("invalid_credentials"),
        },
    )
    .await?;
    tx.commit().await?;
    Ok(())
}

/// Clears successful login throttle buckets.
pub async fn clear_login_throttle(
    client: &Client,
    bucket_sha256: &[&[u8]],
    now: DateTime<Utc>,
) -> Result<(), StoreError> {
    client
        .execute(
            "UPDATE console_auth_throttle
             SET failures = 0, locked_until = NULL, window_started_at = $2, updated_at = $2
             WHERE bucket_sha256 = ANY($1)",
            &[&bucket_sha256, &now],
        )
        .await?;
    Ok(())
}

fn credential_from_row(row: &Row) -> Credential {
    Credential {
        user_id: row.get(0),
        username: row.get(1),
        display_name: row.get(2),
        password_phc: row.get(3),
        enabled: row.get(4),
        auth_generation: row.get(5),
    }
}

fn session_from_row(row: &Row) -> Session {
    Session {
        user_id: row.get(0),
        username: row.get(1),
        display_name: row.get(2),
        csrf_sha256: row.get(3),
        last_seen_at: row.get(4),
        idle_expires_at: row.get(5),
        absolute_expires_at: row.get(6),
        password_must_change: row.get(7),
    }
}

struct AuthAuditEvent<'a> {
    actor: &'a str,
    action: &'a str,
    target: Option<&'a str>,
    result: &'a str,
    actor_kind: Option<&'a str>,
    actor_id: Option<&'a str>,
    actor_display: Option<&'a str>,
    authentication_method: Option<&'a str>,
    target_kind: Option<&'a str>,
    target_id: Option<&'a str>,
    reason_code: Option<&'a str>,
}

async fn append_auth_event(
    tx: &tokio_postgres::Transaction<'_>,
    context: &AuditContext<'_>,
    event: AuthAuditEvent<'_>,
) -> Result<(), StoreError> {
    tx.execute(
        "INSERT INTO audit_log
            (actor, action, target, result, detail, request_id, actor_kind,
             actor_id, actor_display, authentication_method, target_kind,
             target_id, reason_code, source_address, user_agent)
         VALUES ($1, $2, $3, $4,
             CASE WHEN $12::text IS NULL THEN '{}'::jsonb
                  ELSE jsonb_build_object('reason_code', $12::text) END,
             $5, $6, $7, $8, $9, $10, $11, $12, $13::text::inet, $14)",
        &[
            &event.actor,
            &event.action,
            &event.target,
            &event.result,
            &context.request_id,
            &event.actor_kind,
            &event.actor_id,
            &event.actor_display,
            &event.authentication_method,
            &event.target_kind,
            &event.target_id,
            &event.reason_code,
            &context.source_address,
            &context.user_agent,
        ],
    )
    .await?;
    Ok(())
}
