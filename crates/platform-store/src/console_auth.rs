/// User credential data used for constant-shape password verification.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Credential {
    /// Stable local user id.
    pub user_id: String,
    /// Canonical local username.
    pub username: String,
    /// Operator-facing display name.
    pub display_name: String,
    /// Argon2id PHC string.
    pub password_phc: String,
    /// Whether the account can authenticate.
    pub enabled: bool,
    /// Generation captured when the session was created.
    pub auth_generation: i64,
}

/// Values required to provision one local account.
#[derive(Clone, Debug)]
pub struct NewLocalUser<'a> {
    /// User UUID.
    pub user_id: &'a str,
    /// Binding UUID.
    pub binding_id: &'a str,
    /// Canonical username.
    pub username: &'a str,
    /// Operator-facing display name.
    pub display_name: &'a str,
    /// Argon2id PHC string, never a plaintext password.
    pub password_phc: &'a str,
    /// Built-in role id (`viewer`, `analyst`, `operator`, or `admin`).
    pub role_id: &'a str,
    /// Actor identifier for audit.
    pub actor_id: &'a str,
    /// Provisioning time.
    pub now: DateTime<Utc>,
}

/// Hashes and times for one opaque browser session.
#[derive(Clone, Debug)]
pub struct NewSession<'a> {
    /// SHA-256 digest of the browser's random session token.
    pub session_sha256: &'a [u8],
    /// Existing browser session to revoke atomically when rotating after login.
    pub previous_session_sha256: Option<&'a [u8]>,
    /// SHA-256 digest of its synchroniser CSRF value.
    pub csrf_sha256: &'a [u8],
    /// User UUID.
    pub user_id: &'a str,
    /// User authentication generation observed after password verification.
    pub auth_generation: i64,
    /// Creation time.
    pub now: DateTime<Utc>,
    /// Idle expiration.
    pub idle_expires_at: DateTime<Utc>,
    /// Absolute expiration.
    pub absolute_expires_at: DateTime<Utc>,
    /// Trusted request context included in the login audit event.
    pub audit: AuditContext<'a>,
}

/// Hashes and expiry for one one-use local pre-auth value.
#[derive(Clone, Debug)]
pub struct NewPreauth<'a> {
    /// SHA-256 digest of the random pre-auth cookie.
    pub token_sha256: &'a [u8],
    /// SHA-256 digest of the CSRF value.
    pub csrf_sha256: &'a [u8],
    /// SHA-256 digest binding the state to its initiating browser.
    pub browser_sha256: &'a [u8],
    /// Creation time.
    pub created_at: DateTime<Utc>,
    /// Expiry time.
    pub expires_at: DateTime<Utc>,
}

/// Redacted, trusted metadata for an authentication audit event.
#[derive(Clone, Copy, Debug, Default)]
