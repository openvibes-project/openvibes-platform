/// Creates a session only if the enabled account still has the generation
/// whose password was just verified.
pub async fn create_session(
    client: &mut Client,
    session: &NewSession<'_>,
) -> Result<bool, StoreError> {
    let tx = client.transaction().await?;
    tx.query_opt(
        "SELECT user_id FROM console_users
         WHERE user_id = $1::text::uuid AND enabled AND auth_generation = $2
         FOR SHARE",
        &[&session.user_id, &session.auth_generation],
    )
    .await?;
    let inserted = tx
        .execute(
            "INSERT INTO console_sessions
                (session_sha256, csrf_sha256, user_id, auth_generation, created_at,
                 last_seen_at, idle_expires_at, absolute_expires_at)
             SELECT $1, $2, u.user_id, u.auth_generation, $3, $3, $4, $5
             FROM console_users u
             WHERE u.user_id = $6::text::uuid AND u.enabled AND u.auth_generation = $7",
            &[
                &session.session_sha256,
                &session.csrf_sha256,
                &session.now,
                &session.idle_expires_at,
                &session.absolute_expires_at,
                &session.user_id,
                &session.auth_generation,
            ],
        )
        .await?;
    if inserted == 1 {
        if let Some(previous_session_sha256) = session.previous_session_sha256 {
            tx.execute(
                "UPDATE console_sessions SET revoked_at = $2
                 WHERE session_sha256 = $1 AND revoked_at IS NULL",
                &[&previous_session_sha256, &session.now],
            )
            .await?;
        }
        let row = tx
            .query_one(
                "SELECT display_name FROM console_users WHERE user_id = $1::text::uuid",
                &[&session.user_id],
            )
            .await?;
        let display_name: String = row.get(0);
        append_auth_event(
            &tx,
            &session.audit,
            AuthAuditEvent {
                actor: session.user_id,
                action: "auth.login.succeeded",
                target: Some(session.user_id),
                result: "success",
                actor_kind: Some("user"),
                actor_id: Some(session.user_id),
                actor_display: Some(&display_name),
                authentication_method: Some("local_password"),
                target_kind: Some("user"),
                target_id: Some(session.user_id),
                reason_code: None,
            },
        )
        .await?;
    }
    tx.commit().await?;
    Ok(inserted == 1)
}

